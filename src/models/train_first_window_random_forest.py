
from pathlib import Path

import joblib
import numpy as np
import pandas as pd

from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import OneHotEncoder
from sklearn.ensemble import RandomForestRegressor
from sklearn.pipeline import Pipeline
from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    mean_squared_log_error,
)

from src.features.build_features import build_base_features
from src.features.recursive_forecasting import RecursiveFeatureBuilder
from src.models.recursive_forecaster import recursive_forecast
from src.models.feature_config import (
    get_feature_columns,
    CATEGORICAL_FEATURES,
)


ROOT = Path(__file__).resolve().parents[2]

# --------------------------------------------------
# 1. Configuration
# --------------------------------------------------

CUTOFF_DATE = pd.Timestamp("2015-05-08")
VALIDATION_START = pd.Timestamp("2015-05-09")
VALIDATION_END = pd.Timestamp("2015-06-19")

EXPECTED_ROWS = 46_830
EXPECTED_DAYS = 42

# --------------------------------------------------
# 2. Load data
# --------------------------------------------------

train_features = pd.read_pickle(
    ROOT / "data" / "processed" / "train_features.pkl"
)

history_raw = pd.read_pickle(
    ROOT / "data" / "processed" / "train_preprocessed.pkl"
)

for df in (train_features, history_raw):
    df["Date"] = pd.to_datetime(df["Date"])

# Training features strictly through 8 May.
train = train_features.loc[
    (train_features["Date"] <= CUTOFF_DATE)
    & (train_features["Open"] == 1)
].copy()

# Historical information available to the recursive forecaster.
history = history_raw.loc[
    history_raw["Date"] <= CUTOFF_DATE
].copy()

# First-window forecast records from the original training data.
validation_raw = history_raw.loc[
    history_raw["Date"].between(
        VALIDATION_START,
        VALIDATION_END,
    )
].copy()

# Build date/store/business features for the forecast window.
# Recursive sales-history features will be generated by the builder.
validation = build_base_features(validation_raw)

# --------------------------------------------------
# 3. Validate data windows
# --------------------------------------------------

assert not train.empty
assert not history.empty
assert not validation.empty

assert train["Date"].max() <= CUTOFF_DATE
assert history["Date"].max() == CUTOFF_DATE

assert validation["Date"].min() == VALIDATION_START
assert validation["Date"].max() == VALIDATION_END
assert validation["Date"].nunique() == EXPECTED_DAYS
assert len(validation) == EXPECTED_ROWS

assert not train.duplicated(["Store", "Date"]).any()
assert not history.duplicated(["Store", "Date"]).any()
assert not validation.duplicated(["Store", "Date"]).any()

print("Training cutoff:", CUTOFF_DATE.date())
print(
    "Validation window:",
    VALIDATION_START.date(),
    "to",
    VALIDATION_END.date(),
)
print("Training rows available:", len(train))
print("Historical rows:", len(history))
print("Validation rows:", len(validation))
print("Validation dates:", validation["Date"].nunique())

# --------------------------------------------------
# 4. Feature configuration
# --------------------------------------------------

feature_columns = get_feature_columns(train)

categorical_features = [
    col for col in CATEGORICAL_FEATURES
    if col in feature_columns
]

numeric_features = [
    col for col in feature_columns
    if col not in categorical_features
]

# Convert categorical columns consistently.
for col in categorical_features:
    train[col] = train[col].astype(str)
    validation[col] = validation[col].astype(str)

X_train = train[feature_columns]
y_train = train["Sales"].astype(float)

print("\nTraining features:", len(feature_columns))
print("Categorical features:", categorical_features)
print("Numeric features:", len(numeric_features))

# --------------------------------------------------
# 5. Preprocessing + Random Forest
# --------------------------------------------------

preprocessor = ColumnTransformer(
    transformers=[
        (
            "categorical",
            OneHotEncoder(
                handle_unknown="ignore",
                sparse_output=True,
                dtype=np.float32,
            ),
            categorical_features,
        ),
        (
            "numeric",
            Pipeline([
                (
                    "imputer",
                    SimpleImputer(
                        strategy="median",
                        add_indicator=True,
                    ),
                ),
            ]),
            numeric_features,
        ),
    ],
    remainder="drop",
)

rf = RandomForestRegressor(
    n_estimators=100,
    max_depth=20,
    min_samples_leaf=10,
    max_features=0.7,
    bootstrap=True,
    random_state=42,
    n_jobs=-1,
)

model = Pipeline([
    ("preprocessor", preprocessor),
    ("random_forest", rf),
])

# --------------------------------------------------
# 6. Train
# --------------------------------------------------

print("\nTraining first-window Random Forest...")

model.fit(X_train, y_train)

print("Random Forest training completed.")

# --------------------------------------------------
# 7. Recursive forecast
# --------------------------------------------------

print("\nStarting first-window recursive forecast...")

builder = RecursiveFeatureBuilder(history)

forecast = recursive_forecast(
    base_data=validation,
    feature_builder=builder,
    model=model,
    feature_columns=feature_columns,
)

# --------------------------------------------------
# 8. Independent Store-Date alignment
# --------------------------------------------------

forecast_eval = forecast[
    ["Store", "Date", "Sales", "PredictedSales"]
].rename(
    columns={"Sales": "ForecastAttachedSales"}
)

validation_actual = validation[
    ["Store", "Date", "Sales"]
].rename(
    columns={"Sales": "ActualSales"}
)

evaluation = forecast_eval.merge(
    validation_actual,
    on=["Store", "Date"],
    how="outer",
    validate="one_to_one",
    indicator=True,
)

assert len(evaluation) == EXPECTED_ROWS
assert evaluation["_merge"].eq("both").all()

assert np.allclose(
    evaluation["ForecastAttachedSales"],
    evaluation["ActualSales"],
)

print("\nStore-Date alignment: PASS")
print("Rows evaluated:", len(evaluation))

# --------------------------------------------------
# 9. Evaluation metrics
# --------------------------------------------------

actual = evaluation["ActualSales"].to_numpy(dtype=float)
predictions = evaluation["PredictedSales"].to_numpy(dtype=float)

assert np.isfinite(actual).all()
assert np.isfinite(predictions).all()
assert (actual >= 0).all()
assert (predictions >= 0).all()
assert actual.sum() > 0

mae = mean_absolute_error(actual, predictions)
rmse = np.sqrt(mean_squared_error(actual, predictions))
wmape = np.abs(actual - predictions).sum() / actual.sum()
rmsle = np.sqrt(
    mean_squared_log_error(actual, predictions)
)

print("\nFirst-window Random Forest results")
print("----------------------------------")
print(f"MAE:   {mae:.4f}")
print(f"RMSE:  {rmse:.4f}")
print(f"WMAPE: {wmape:.4%}")
print(f"RMSLE: {rmsle:.4f}")

# --------------------------------------------------
# 10. Save separate first-window artifacts
# --------------------------------------------------

processed_dir = ROOT / "data" / "processed"
reports_dir = ROOT / "reports"

processed_dir.mkdir(exist_ok=True)
reports_dir.mkdir(exist_ok=True)

model_path = (
    processed_dir / "first_window_random_forest_model.joblib"
)

predictions_path = (
    processed_dir / "first_window_random_forest_predictions.csv"
)

metrics_path = (
    reports_dir / "first_window_random_forest_results.csv"
)

importance_path = (
    reports_dir / "first_window_random_forest_feature_importance.csv"
)

joblib.dump(
    {
        "model": model,
        "feature_columns": feature_columns,
        "categorical_features": categorical_features,
        "numeric_features": numeric_features,
        "training_rows": len(train),
        "training_cutoff": str(CUTOFF_DATE.date()),
        "random_state": 42,
    },
    model_path,
)

forecast.to_csv(predictions_path, index=False)

metrics = pd.DataFrame([{
    "Model": "RandomForest",
    "MAE": mae,
    "RMSE": rmse,
    "WMAPE": wmape,
    "RMSLE": rmsle,
    "RowsEvaluated": len(evaluation),
    "StoreDateAlignment": "PASS",
    "ValidationType": "Recursive",
    "ValidationStart": str(VALIDATION_START.date()),
    "ValidationEnd": str(VALIDATION_END.date()),
    "TrainingCutoff": str(CUTOFF_DATE.date()),
    "TrainingRows": len(train),
}])

metrics.to_csv(metrics_path, index=False)

# --------------------------------------------------
# 11. Feature importance
# --------------------------------------------------

feature_names = (
    model.named_steps["preprocessor"].get_feature_names_out()
)

importance = (
    model.named_steps["random_forest"].feature_importances_
)

importance_df = pd.DataFrame({
    "Feature": feature_names,
    "Importance": importance,
}).sort_values(
    "Importance",
    ascending=False,
)

importance_df.to_csv(importance_path, index=False)

print("\nTop 15 Random Forest features:")
print(importance_df.head(15).to_string(index=False))

print("\nSaved:")
print(model_path)
print(predictions_path)
print(metrics_path)
print(importance_path)
